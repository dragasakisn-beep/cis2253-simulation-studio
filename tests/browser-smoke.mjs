import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
const base=process.env.CIS2253_BASE_URL||'http://127.0.0.1:4173/';
const output='test-output';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:900}, deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Cyber Ethics Simulation Studio'}).waitFor();
 assert.equal(await page.locator('article.card').count(),8);
 assert.equal(await page.locator('.hero-resources .resource-card').count(),3);
 const img=await page.request.get(new URL('assets/photography/cis2253-ethics-hero.webp',base).href);
 assert.equal(img.status(),200);
 assert.ok((await img.body()).length>50000);
 const css=await page.request.get(new URL('assets/cis2253-theme.css',base).href);
 assert.equal(css.status(),200);
 const imageURL=await page.locator('.dashboard-title').evaluate(el=>getComputedStyle(el).backgroundImage);
 assert.match(imageURL,/cis2253-ethics-hero\.webp/);
 await page.screenshot({path:output+'/home-desktop.png',fullPage:true});
 await page.locator('.hero-resources [data-library="0"]').click();
 await page.getByRole('heading',{name:'Reference Library'}).waitFor();
 await page.getByRole('button',{name:/Back to scenarios/}).click();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('heading',{name:'Cyber Ethics Simulation Studio'}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile horizontal overflow');
 await page.screenshot({path:output+'/home-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:900});
 await page.getByRole('button',{name:/Open scenario: The Sign-Off|Open scenario|Start lab/i}).first().click();
 await page.getByRole('heading',{name:'Enter your name to continue'}).waitFor();
 await page.locator('input[name="student"]').fill('QA Test Student');
 await page.locator('form#student-form button[type="submit"]').click();
 await page.getByRole('heading',{name:'The Sign-Off'}).waitFor();
 assert.ok(await page.locator('.activity').count());
 await page.screenshot({path:output+'/case-activity.png',fullPage:false});
 assert.deepEqual(errors,[]);
 console.log('PASS: hero assets, eight scenarios, reference navigation, mobile viewport, start Lab 1');
} finally { await browser.close(); }
